/*
 * backends/css/render.c — Stage 5a (docs/IMPLEMENTATION.md): mirrors
 * `arklight.backend.css.render` (Rae-ARK/ARKlight, cloned separately
 * as reference). Of Stage 5's two backends, CSS is the narrower port
 * per IMPLEMENTATION.md's own note: a closed, static default
 * stylesheet with no per-node CSS generation yet, carried over
 * closest to as-is of anything in v1.
 *
 * Unlike the HTML backend (Stage 4), this backend's output does not
 * depend on `site`/`ir` at all — ARKlight-py's CSSBackend.render(ir)
 * accepts `ir` only to satisfy the Backend interface and leaves it
 * unconsulted (see render.py's own comment: "`ir` isn't consulted
 * yet -- reserved for a future per-node style collection pass"). This
 * port matches that: BASE_CSS below is emitted verbatim regardless of
 * what `site` contains, including a NULL site — there is no
 * "nothing to render" case for this backend the way there is for
 * ark_html_render, because there is nothing IR-shaped to be empty.
 *
 * Per ADDENDUM.md §4.1, this file only ever reaches ArkSite/
 * ArkBuildResult through carklight.h — never core/internal.h.
 */

