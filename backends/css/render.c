/* Allocation goes through core/alloc.c's public ark_alloc as of
 * Stage 5e — see carklight.h's "Stage 5e" block comment. */
static char* err_dup(const char* msg) {
    size_t len = strlen(msg) + 1;
    char* copy = ark_alloc(len);
    if (copy != NULL) {
        memcpy(copy, msg, len);
    }
    return copy;
}

int ark_css_render(ArkBackend* self, const ArkSite* site,
                    ArkBuildResult* out, char** err_out) {
    (void)self; /* no per-instance state (matches ark_html_render) */
    (void)site; /* deliberately unconsulted — see this file's header comment */

    if (err_out != NULL) {
        *err_out = NULL;
    }
    if (out == NULL) {
        if (err_out != NULL) {
            *err_out = err_dup("ark_css_render: out is NULL");
        }
        return 1;
    }

    int add_rc = ark_build_result_add_file(out, ARK_CSS_STYLESHEET_PATH,
        (const uint8_t*)ARK_BASE_CSS, strlen(ARK_BASE_CSS));
    if (add_rc != 0) {
        if (err_out != NULL) {
            *err_out = err_dup("ark_css_render: failed to store output file");
        }
        return 1;
    }

    return 0;
}

